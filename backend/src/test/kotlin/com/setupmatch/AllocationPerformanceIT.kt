    @Test

    fun `benchmark allocation with five thousand items and ten five-slot policies`() {

        val representativeSlots = representativePolicy.slots



        repeat(WARMUP) {

            loadAndLock(representativeSlots)

            benchmarkCandidates = loadAndLock(representativeSlots).map { it.toCandidate() }

            runSingleHungarianMatcher()

            runAllPoliciesHungarian()

        }



        selectLockedMs = medianMillis(ITERATIONS) {

            loadAndLock(representativeSlots)

        }



        benchmarkCandidates = loadAndLock(representativeSlots).map { it.toCandidate() }



        singleMatcherMs = medianMillis(ITERATIONS) { runSingleHungarianMatcher() }

        allocatorHungarianMs = medianMillis(ITERATIONS) { runAllPoliciesHungarian() }

        for (policy in benchmarkPolicies) {

            val outcome = HungarianAllocator.allocate(policy.slots, benchmarkCandidates)

            assertTrue(outcome is AllocationOutcome.Success, "hungarian failed: ${policy.name}")

        }



        endToEndSingleMs = medianMillis(ITERATIONS) {

            runSingleEndToEndWithRollback(representativePolicy)

        }

        endToEndTenPoliciesMs = medianMillis(ITERATIONS) {

            runAllEndToEndWithRollback()

        }

    }



    private fun runSingleHungarianMatcher() {

        val outcome = HungarianAllocator.allocate(representativePolicy.slots, benchmarkCandidates)

        assertTrue(outcome is AllocationOutcome.Success)

    }



    private fun runAllPoliciesHungarian() {

        for (policy in benchmarkPolicies) {

            val outcome = HungarianAllocator.allocate(policy.slots, benchmarkCandidates)

            assertTrue(outcome is AllocationOutcome.Success)

        }

    }



    private fun runSingleEndToEndWithRollback(policy: BenchmarkPolicy) {

        TransactionTemplate(transactionManager).execute { status ->

            allocationService.create(

                CreateAllocationRequest(

                    employeeId = "perf-single-${UUID.randomUUID()}",

                    policy = policy.requestPolicy,

                ),

            )

            status.setRollbackOnly()

            null

        }

    }



    private fun runAllEndToEndWithRollback() {

        TransactionTemplate(transactionManager).execute { status ->

            for (policy in benchmarkPolicies) {

                allocationService.create(

                    CreateAllocationRequest(

                        employeeId = "perf-${policy.name}-${UUID.randomUUID()}",

                        policy = policy.requestPolicy,

                    ),

                )

            }

            status.setRollbackOnly()

            null

        }

    }



    private fun loadAndLock(slots: List<PolicySlot>) =

        TransactionTemplate(transactionManager).execute {

            equipmentAllocationLoader.loadAndLockAvailable(slots)

        } ?: emptyList()



    private fun com.setupmatch.domain.EquipmentEntity.toCandidate() = EquipmentCandidate(

