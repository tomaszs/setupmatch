    private data class SeedRow(

        val id: UUID,

        val type: String,

        val brand: String,

        val model: String,

        val conditionScore: BigDecimal,

        val purchaseDate: LocalDate,

    )



    private fun buildSeedRows(totalItems: Int): List<SeedRow> {

        val brands = listOf("Apple", "Dell", "Lenovo", "Logitech", "LG", "Samsung", "Keychron", "Razer")

        val types = EquipmentType.entries

        val perType = totalItems / types.size



        return types.flatMap { type ->

            (0 until perType).map { index ->

                val condition = when (type) {

                    EquipmentType.monitor -> monitorCondition(index, perType)

                    else -> genericCondition(index, perType)

                }

                SeedRow(

                    id = UUID.nameUUIDFromBytes("perf-$type-$index".toByteArray()),

                    type = type.name,

                    brand = brands[(index + type.ordinal) % brands.size],

                    model = "${type.name}-$index",

                    conditionScore = condition,

                    purchaseDate = when (type) {
                        EquipmentType.monitor -> if (index == 0) {
                            LocalDate.of(2024, 6, 1)
                        } else {
                            LocalDate.of(2019, 1, 1).plusDays(index.toLong())
                        }
                        else -> LocalDate.of(2020, 1, 1).plusDays((index + type.ordinal * 7).toLong())
                    },

                )

            }

        }

    }



    private fun monitorCondition(index: Int, perType: Int): BigDecimal {
        if (index == 0) {
            return BigDecimal.valueOf(0.86)
        }

        val lowIndex = index - 1
        val lowSpan = perType - 2
        val step = if (lowSpan > 0) 0.22 / lowSpan else 0.0

        return BigDecimal.valueOf(0.55 + lowIndex * step).coerceAtMost(BigDecimal.valueOf(0.77))
    }



    private fun genericCondition(index: Int, perType: Int): BigDecimal {

        val step = if (perType > 1) 0.44 / (perType - 1) else 0.0



        return BigDecimal.valueOf(0.55 + index * step)

    }



