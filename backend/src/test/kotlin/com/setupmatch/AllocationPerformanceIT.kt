    @BeforeAll

    fun seedInventory() {

        jdbcTemplate.execute("DELETE FROM allocation_line")

        jdbcTemplate.execute("DELETE FROM allocation_request")

        jdbcTemplate.execute("DELETE FROM equipment")



        val rows = buildSeedRows(TOTAL_ITEMS)

        val batchSize = 500

        rows.chunked(batchSize).forEach { chunk ->

            jdbcTemplate.batchUpdate(

                """

                INSERT INTO equipment (id, type, brand, model, state, condition_score, purchase_date)

                VALUES (?, ?, ?, ?, 'available', ?, ?)

                """.trimIndent(),

                object : BatchPreparedStatementSetter {

                    override fun setValues(ps: PreparedStatement, index: Int) {

                        val row = chunk[index]

                        ps.setObject(1, row.id)

                        ps.setString(2, row.type)

                        ps.setString(3, row.brand)

                        ps.setString(4, row.model)

                        ps.setBigDecimal(5, row.conditionScore)

                        ps.setObject(6, row.purchaseDate)

                    }



                    override fun getBatchSize(): Int = chunk.size

                },

            )

        }



        benchmarkPolicies = benchmarkPolicyDefinitions()

        representativePolicy = benchmarkPolicies.first()

    }



